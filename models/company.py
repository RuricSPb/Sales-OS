class Company:

    def __init__(
        self,
        object_id=None,
        company_name="",
        company_type="",
        contact="",
        phone="",
        email=""
    ):

        self.object_id = object_id

        self.company_name = company_name

        self.company_type = company_type

        self.contact = contact

        self.phone = phone

        self.email = email